import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const PROJECT_ROOT = path.join(__dirname, '..')

function generateComprehensiveMarkdown() {
  const scenariosPath = path.join(PROJECT_ROOT, 'public', 'scenarios.json')
  
  if (!fs.existsSync(scenariosPath)) {
    console.error('scenarios.json not found. Run scan-project.js first.')
    process.exit(1)
  }

  const { scenarios, stats } = JSON.parse(fs.readFileSync(scenariosPath, 'utf-8'))

  const categories = [...new Set(scenarios.map(s => s.category))].sort()

  let markdown = `# SF Architect Showcase - Comprehensive Scenarios Document\n\n`
  markdown += `**Generated:** ${new Date().toISOString()}\n`
  markdown += `**Project:** Salesforce Architecture Showcase - Global Automotive Manufacturer\n`
  markdown += `**Source Files Scanned:** ${stats.files} markdown files\n`
  markdown += `**Total Scenarios Extracted:** ${stats.scenarios}\n`
  markdown += `**Categories Identified:** ${stats.categories}\n\n`
  markdown += `---\n\n`

  markdown += `## Table of Contents\n\n`
  categories.forEach((cat, i) => {
    markdown += `${i + 1}. [${cat}](#${cat.toLowerCase().replace(/\s+/g, '-')})\n`
  })
  markdown += `\n---\n\n`

  markdown += `## Executive Summary\n\n`
  markdown += `This document consolidates all architectural scenarios, decisions, designs, and operational considerations `
  markdown += `for the **"One Customer. One Vehicle. One Experience."** transformation initiative. `
  markdown += `A global automotive manufacturer has acquired six EV companies across North America, Europe, Japan, `
  markdown += `South Korea, Australia, and Brazil, operating 14 vehicle brands across 47 countries with 68M customers `
  markdown += `and 125M connected vehicles.\n\n`
  markdown += `The scenarios are organized by architectural domain to support decision-making, governance, and delivery planning.\n\n`
  markdown += `---\n\n`

  categories.forEach(category => {
    const catScenarios = scenarios.filter(s => s.category === category)
    const anchor = category.toLowerCase().replace(/\s+/g, '-')
    
    markdown += `## ${category} {#${anchor}}\n\n`
    markdown += `**${catScenarios.length} scenarios** | Source files: ${catScenarios.map(s => s.file).join(', ')}\n\n`

    catScenarios.forEach((scenario, index) => {
      markdown += `### ${index + 1}. ${scenario.title}\n\n`
      markdown += `**Source:** \`${scenario.file}\`  \n`
      markdown += `**Tags:** ${scenario.tags.map(t => `\`${t}\``).join(', ')}\n\n`
      markdown += `${scenario.description}\n\n`
      
      const filePath = path.join(PROJECT_ROOT, scenario.file)
      if (fs.existsSync(filePath)) {
        const fullContent = fs.readFileSync(filePath, 'utf-8')
        const keySections = extractKeySections(fullContent)
        if (keySections.length > 0) {
          markdown += `#### Key Sections\n\n`
          keySections.forEach(section => {
            markdown += `- ${section}\n`
          })
          markdown += `\n`
        }
      }
      
      markdown += `---\n\n`
    })
  })

  markdown += `## Cross-Cutting Concerns\n\n`
  markdown += `### Data Residency & Sovereignty\n`
  markdown += `- Multiple countries with strict data residency requirements\n`
  markdown += `- Regional data zones strategy (ADR-005)\n`
  markdown += `- Zero-copy data access patterns\n\n`

  markdown += `### Acquisition Readiness\n`
  markdown += `- Architecture must accommodate 2+ additional EV manufacturers\n`
  markdown += `- Single org strategy with extensible data model (ADR-001)\n`
  markdown += `- Event-driven architecture for loose coupling (ADR-007)\n\n`

  markdown += `### Cost Optimization\n`
  markdown += `- 25% reduction in annual technology spending\n`
  markdown += `- Consolidation of 4 ERP ecosystems, 3 identity providers\n`
  markdown += `- Shared services and platform approach\n\n`

  markdown += `### Business Continuity\n`
  markdown += `- Zero-downtime transformation requirement\n`
  markdown += `- Independent operations during transition (legal constraint)\n`
  markdown += `- Dealer integration freeze for 2 years\n\n`

  markdown += `---\n\n`
  markdown += `## Appendix: Source File Inventory\n\n`
  markdown += `| Category | File | Scenarios |\n`
  markdown += `|----------|------|-----------|\n`

  const fileMap = {}
  scenarios.forEach(s => {
    if (!fileMap[s.file]) fileMap[s.file] = { category: s.category, count: 0 }
    fileMap[s.file].count++
  })

  Object.entries(fileMap)
    .sort((a, b) => a[1].category.localeCompare(b[1].category))
    .forEach(([file, info]) => {
      markdown += `| ${info.category} | ${file} | ${info.count} |\n`
    })

  markdown += `\n---\n\n`
  markdown += `*Document generated by SF Architect Showcase Scenario Scanner*\n`
  markdown += `*For architectural review and governance purposes*\n`

  const outputPath = path.join(PROJECT_ROOT, 'COMPREHENSIVE_SCENARIOS.md')
  fs.writeFileSync(outputPath, markdown)
  console.log(`Comprehensive scenarios document written to ${outputPath}`)
  console.log(`File size: ${(markdown.length / 1024).toFixed(1)} KB`)
}

function extractKeySections(content) {
  const sections = []
  const lines = content.split('\n')
  
  for (const line of lines) {
    const match = line.match(/^##\s+(.+)$/)
    if (match) {
      sections.push(match[1].trim())
    }
  }
  
  return sections.slice(0, 10)
}

generateComprehensiveMarkdown()